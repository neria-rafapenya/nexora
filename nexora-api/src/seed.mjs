export async function seedCatalog(store, tenantId, actorId) {
  // Explicitly called only for a fresh workspace; deterministic SKUs make re-runs safe.
  for (const [fi, [name, temperature, names]] of demoFamilies.entries()) {
    let family = (await store.list(tenantId, "families")).find(
      (x) => x.data.name === name,
    );
    if (!family)
      family = await store.create(
        tenantId,
        "families",
        { name, temperature, parentId: null },
        actorId,
      );
    for (const [pi, title] of names.entries()) {
      const sku = `NX-${String(fi + 1).padStart(2, "0")}-${String(pi + 1).padStart(3, "0")}`;
      if (
        (await store.list(tenantId, "products")).some((x) => x.data.sku === sku)
      )
        continue;
      await store.create(
        tenantId,
        "products",
        {
          sku,
          ean: null,
          name: title,
          brand: "Nexora Sample",
          familyId: family.id,
          supplierId: null,
          format: "1 kg pack",
          unit: "KG",
          netWeightGrams: 1000,
          portions: 10,
          price: Number((1.5 + fi * 1.8 + pi * 0.37).toFixed(2)),
          stock: 20 + pi * 5,
          shelfLifeDays:
            temperature === "AMBIENT"
              ? 365
              : temperature === "FROZEN"
                ? 180
                : 14,
          temperature,
          ingredients: null,
          ownBrand: false,
          glutenFree: false,
          pureedSuitable: false,
          active: true,
          allergenStatus: "UNVERIFIED",
        },
        actorId,
      );
    }
  }
}
