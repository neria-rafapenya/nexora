const text = (label, required = false) => ({ label, type: "text", required });
const num = (label, required = false) => ({
  label,
  type: "number",
  integer: true,
  min: 0,
  required,
});
const ref = (label, resource, required = true) => ({
  label,
  type: "relation",
  resource,
  required,
});
const choice = (label, options) => ({
  label,
  type: "select",
  options,
  required: true,
});
const json = (label) => ({ label, type: "json" });
